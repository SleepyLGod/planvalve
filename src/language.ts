export function ui(language: Language = "zh") {
  const t = (text: string): string =>
    language === "en"
      ? (english[text] ?? text)
      : ((
          {
            configured: "已配置",
            authorized: "已授权",
            "refresh-required": "需要续期",
            "login-required": "需要登录",
            closed: "已关闭",
          } as Record<string, string>
        )[text] ?? text);
  const count = (value: unknown): string =>
    typeof value === "number" ? value.toLocaleString("en-US") : t("未知");
  const duration = (start?: string, end?: string): string => {
    if (!start) return "—";
    const n = Math.max(
      0,
      Date.parse(end ?? new Date().toISOString()) - Date.parse(start),
    );
    return n < 1000
      ? `${n} ${t("毫秒")}`
      : `${(n / 1000).toFixed(1)} ${t("秒")}`;
  };
  const states: Record<string, string> = {
    queued: "排队中",
    running: "执行中",
    completed: "已完成",
    failed: "失败",
    unknown: "未确认",
    cancelled: "已取消",
    expired: "已过期",
    rejected: "已拒绝",
  };
  return {
    t,
    count,
    duration,
    stateLabel: (state: string) => t(states[state] ?? state),
  };
}
